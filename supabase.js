function resolveIngredient(input) {
  const lower = input.toLowerCase().trim();
  // Ищем в словаре синонимов
  if (INGREDIENT_SYNONYMS[lower]) {
    return INGREDIENT_SYNONYMS[lower];
  }
  // Возвращаем как есть
  return [lower];
}

function resolveIngredients(inputs) {
  // Для каждого слова возвращаем массив вариантов
  return inputs.map(i => resolveIngredient(i));
}

